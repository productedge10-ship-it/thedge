/* ==================================================================
   Повернення людини з платіжної сторінки.

   Здавалося б, зайва ланка: чому не вести одразу на /app?

   Бо WayForPay повертає браузер не посиланням, а POST-запитом — він
   кладе в тіло результат платежу. А Netlify віддає статику лише на
   GET: POST у /app для нього означає «такої сторінки немає», і
   людина після успішної оплати бачить чужу 404. Найгірший можливий
   екран у цей момент: гроші пішли, а продукт каже «нічого немає».

   Тому тут стоїть обробник, який приймає POST і відповідає 303. Це
   не просто редирект: саме 303 зобовʼязує браузер піти за новою
   адресою методом GET. З 302 частина браузерів повторила б POST — і
   ми впали б у ту саму 404, тільки на крок далі.

   --------------------------------------------------------------
   Що тут НЕ відбувається: нічого не вмикається.

   У тілі цього запиту лежить «оплачено», і спокуса прочитати його й
   одразу видати Pro велика. Але цей запит іде через браузер людини,
   тобто його можна скласти руками — відкрити консоль і надіслати
   собі «Approved». Доступ дає тільки wfp-callback, який WayForPay
   шле зі свого сервера й підписує ключем.

   Звідси й безглуздий на вигляд рядок нижче: ми свідомо викидаємо
   тіло запиту, не заглядаючи в нього.
================================================================== */

export default async (req) => {
  const site = (process.env.SITE_URL || '').replace(/\/+$/, '');

  /* Тіло не читаємо принципово — див. вище. */
  const to = `${site}/app?paid=1`;

  return new Response(null, {
    status: 303,
    headers: { location: to },
  });
};
