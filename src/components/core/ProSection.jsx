import useSubscription from '../../hooks/useSubscription';
import ProGate from '../modals/ProGate';
import { startCheckout } from '../../lib/billing';

/* ==================================================================
   Обгортка платного розділу.

   Одне місце, де вирішується «показати вміст чи замок», і одна
   поведінка на всі розділи. Розкидати цю перевірку по сторінках
   означало б п'ять різних замків, з яких один обов'язково забудуть
   оновити.

   --------------------------------------------------------------
   Чого ця обгортка НЕ робить — не охороняє дані.

   Перевірка в браузері — підказка для чесної людини, і не більше:
   код видно в DevTools, і `isPro` там ставиться в true за
   півхвилини. Справжній замок стоїть у базі: `is_pro()` і політики
   RLS на платних таблицях. Якщо для нового платного розділу таких
   політик немає — ця обгортка його не захищає, вона лише малює
   замочок.

   --------------------------------------------------------------
   Поки відповідь про підписку не прийшла — не показуємо нічого.

   Обидві поспішні відповіді погані. Замок на Pro-акаунті — образа
   людині, яка щойно заплатила. Відкритий розділ, який через секунду
   закривається в неї на очах, — гірше: це виглядає як поломка, і
   саме з цим ідуть у підтримку.
================================================================== */
export default function ProSection({ feature, children }) {
  const sub = useSubscription();

  if (!sub.ready) {
    /* Висота приблизно як у вмісту — щоб сторінка не стрибала, коли
       відповідь прийде. */
    return <div style={{ minHeight: 420 }} />;
  }

  if (sub.isPro) return children;

  return (
    <ProGate
      feature={feature}
      onStart={() => startCheckout('pro_monthly', { trial: true })}
    />
  );
}
