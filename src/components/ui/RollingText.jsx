/* ==================================================================
   Текст, що перекочується по літерах.

   Прийом із «дорогих» кнопок: кожна літера — окреме віконце заввишки
   в рядок, усередині якого одна над одною стоять стара й нова літери.
   Під курсором стовпчик їде вгору, і слово ЗАМІНЮЄТЬСЯ на інше —
   літера за літерою, зліва направо.

   Чому саме так, а не звичайне «зникло-зʼявилось»: зникання читається
   як «текст пішов», а перекочування — як «текст змінився». Різниця
   в один кадр, а відчуття протилежні.

   ------------------------------------------------------------------
   Чому рахуємо словами, а не суцільним рядком

   Перша версія добивала коротший рядок пробілами й котила все підряд.
   На парі «Новий аналіз» → «Почати запис» це ламалось: пробіл у них
   стоїть на різних позиціях, тож у колонці №5 зверху був пробіл, а
   знизу літера — і посеред слова зʼявлялась друга дірка. Виглядало
   як «Почати  запис».

   Тому пара збирається послівно: кожне слово вирівнюється зі своїм,
   а проміжок між словами лишається справжнім і незмінним.
================================================================== */

const NBSP = ' ';

/* Слово добиваємо нерозривними пробілами: вони не схлопуються, тож
   віконця тримають ширину й нічого не стрибає. */
const padWord = (w, len) => [...w.padEnd(len, NBSP)];

export default function RollingText({ from, to, className = '' }) {
  const a = from.split(' ');
  const b = to.split(' ');
  const count = Math.max(a.length, b.length);

  /* Наскрізний лічильник літер: хвиля має йти по всій фразі зліва
     направо, а не починатись заново в кожному слові. */
  let index = 0;

  const words = Array.from({ length: count }, (_, w) => {
    const top = a[w] || '';
    const bottom = b[w] || '';
    const len = Math.max(top.length, bottom.length);
    return { top: padWord(top, len), bottom: padWord(bottom, len) };
  });

  return (
    /* aria-label на контейнері й aria-hidden на літерах: скрінрідер
       має почути фразу, а не дванадцять окремих букв. */
    <span className={`roll ${className}`} aria-label={from}>
      {words.map((word, w) => (
        <span className="roll-word" key={w}>
          {word.top.map((ch, i) => {
            const delay = index++;
            return (
              <span className="roll-col" key={i} aria-hidden="true">
                <span className="roll-stack" style={{ '--i': delay }}>
                  <span className="roll-ch">{ch}</span>
                  <span className="roll-ch">{word.bottom[i]}</span>
                </span>
              </span>
            );
          })}
        </span>
      ))}
    </span>
  );
}
