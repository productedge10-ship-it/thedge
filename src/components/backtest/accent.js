/* ==================================================================
   Колір головної дії в бектестах.

   Акцент застосунку (#8b7bff) — світла лаванда: на великій заливці
   вона бліда й не тримає ваги «головної кнопки». У макеті розділу
   глибший синьо-фіолетовий, і саме він відрізняє дію та акценти
   бектестів від решти інтерфейсу.

   Літерали, а не токени теми, свідомо: це колір конкретних елементів
   розділу, а не відтінок теми. При перемиканні на світлу тему він
   має лишитись таким самим — білий текст працює на обох.

   Живе окремим файлом, бо потрібен у трьох місцях одразу: на
   сторінці, в картці й у модалці створення. Розкидані копії
   розʼїхались би при першій же правці.
================================================================== */

