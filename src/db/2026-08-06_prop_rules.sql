-- EDGE JOURNAL — правила пропа на рахунку
-- Виконати у Supabase → SQL Editor. Ідемпотентний.
--
-- Без цих трьох чисел неможливо відповісти на щоденне питання
-- проп-трейдера: «з моєю статистикою — які шанси дійти до виплати, а
-- які злити на денному ліміті». Баланс у нас є, історія угод є, а
-- меж, які не можна переступати, немає.
--
-- У відсотках, а не в грошах. Проп-фірми так їх і формулюють («5%
-- денного, 10% загального»), і при апгрейді рахунку зі 100K на 200K
-- відсоток лишається той самий — а сума змінилась би, і її довелось
-- би переписувати руками.
--
-- Порожньо за замовчуванням, а не «типові» 5/10/8: підставлене число
-- виглядає як щось перевірене, і людина не помітить, що воно чуже.
-- Краще спитати один раз.
-- ==================================================================

alter table public.prop_accounts
  -- Скільки можна втратити за добу, у % від стартового балансу
  add column if not exists daily_loss_pct numeric;

alter table public.prop_accounts
  -- Максимальна загальна просадка, у % від стартового балансу
  add column if not exists max_drawdown_pct numeric;

alter table public.prop_accounts
  -- Ціль по прибутку для проходження етапу, у %
  add column if not exists profit_target_pct numeric;
