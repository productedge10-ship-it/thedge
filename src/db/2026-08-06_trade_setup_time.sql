--
-- Три розділи аналітики вже написані й працюють, але показують
-- порожнечу — не тому, що зламані, а тому, що журнал не збирає для
-- них даних. `lib/analyticsStore.js` досі віддає setup: null,
-- hour: null, holdMin: null, і через це:
--
--   • «які сетапи заробляють» — головне питання, заради якого ведуть
--     журнал, — залишалось без відповіді (bySetup завжди порожній);
--   • розподіл по годинах не будувався взагалі;
--   • «виходжу зарано чи засиджуюсь» не рахувалось.
--
-- Ціна питання — три поля у формі. Жодна нова фіча не дає такого
-- співвідношення, бо тут нема чого пояснювати новачку: розділи вже
-- на місці, вони просто мовчали.
