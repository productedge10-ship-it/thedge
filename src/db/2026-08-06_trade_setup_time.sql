-- Сетап вільним текстом, а не переліком. Своя назва сетапу — частина
-- системи трейдера, і нав'язаний список або не збігається з його
-- мовою, або змушує підганяти під чуже. Підказки в інтерфейсі
-- збираються з його ж попередніх відповідей.
alter table public.trades
  add column if not exists setup text;

-- Два моменти часу, а не тривалість: обидва видно в терміналі, а
-- тривалість з них рахується сама. Питати «скільки тримав» означало
-- б просити людину порахувати те, що ми можемо порахувати за неї.
alter table public.trades
  add column if not exists entry_time time;

alter table public.trades
  add column if not exists exit_time time;

-- Розріз по сетапах читається постійно і завжди в межах користувача
create index if not exists trades_user_setup_idx
  on public.trades (user_id, setup)
  where setup is not null;
