-- ------------------------------------------------------------------
-- Нагадування про новини — у Telegram
--
-- Черга `tg_alerts` уже є, і бот вичерпує її кожні 30 секунд. Тому
-- новинні нагадування нічого нового в боті не потребують: достатньо
-- класти їх у ту саму чергу.
--
-- Бракує одного — способу впізнати свій рядок. Людина може змінити
-- час попередження або зняти дзвіночок, і тоді старий рядок треба
-- знайти й прибрати. Тримати для цього id події в тексті повідомлення
-- означало б розбирати текст, щоб зрозуміти, що видаляти.
-- ------------------------------------------------------------------

alter table public.tg_alerts
  add column if not exists source text not null default 'manual',
  add column if not exists source_id text;

-- Одна подія — одне нагадування. Повторне вмикання дзвіночка має
-- перезаписати час, а не додати другий рядок на ту саму новину.
create unique index if not exists tg_alerts_source_uniq
  on public.tg_alerts (user_id, source, source_id)
  where source_id is not null;
