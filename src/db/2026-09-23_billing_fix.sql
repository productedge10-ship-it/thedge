-- ------------------------------------------------------------------
-- Відмітка «тріал уже був»
-- ------------------------------------------------------------------
-- Тріал — один на акаунт, і вирішує це сервер (wfp-pay), звіряючись
-- саме з цією колонкою. Без неї достатньо скасувати підписку й
-- натиснути кнопку знову — і так щомісяця за одиницю.
alter table public.subscriptions
  add column if not exists trial_used_at timestamptz;

-- ------------------------------------------------------------------
-- Чи є доступ просто зараз
-- ------------------------------------------------------------------
-- Було: доступ лише в станах active і trialing.
--
-- Проблема: `past_due` і `canceled` — це не «доступу немає», а
-- «доступ до valid_until, але з приміткою». Людина, в якої не пройшло
-- чергове списання, заплатила за період, що ще триває; людина, яка
-- скасувала, — теж. Відібрати Pro в мить невдалого списання чи
-- скасування означало б забрати те, за що вже заплачено. Межу тут
-- тримає одна лише дата, і так і задумано: коли гроші перестануть
-- надходити, valid_until вичерпається сам.
--
-- Друге: питати можна тільки про себе. Функція security definer і
-- приймала будь-який uuid — тобто будь-хто залогінений міг перебрати
-- чужі акаунти й дізнатись, хто з них платить. Службовий ключ (воркер,
-- серверні функції) питати про інших може й далі.
create or replace function public.is_pro(p_user uuid default auth.uid())
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.subscriptions s
     where s.user_id = p_user
       and (p_user = auth.uid() or auth.role() = 'service_role')
       and s.plan = 'pro'
       and s.status in ('active', 'trialing', 'past_due', 'canceled')
       and (s.valid_until is null or s.valid_until > now())
  );
$$;

grant execute on function public.is_pro(uuid) to authenticated;
