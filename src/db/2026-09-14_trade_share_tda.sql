-- ------------------------------------------------------------------
-- TDA-розбір у публічному посиланні на угоду
--
-- За замовчуванням розбір дня чужим не показуємо: людина ділиться
-- однією угодою, а не всією своєю підготовкою. Вмикається кнопкою в
-- картці угоди, вимикається тією ж кнопкою будь-коли.
--
-- Чому знімок, а не посилання на trading_plans: план лишається
-- приватним, і давати анонові право читати його рядок заради однієї
-- угоди — це відкрити весь план дня, включно з тим, чим людина не
-- ділилась. Тому при вмиканні кладемо в саму угоду копію блоків
-- саме такими, якими вони були на момент публікації.
-- ------------------------------------------------------------------

alter table public.trades
  add column if not exists share_tda boolean not null default false,
  add column if not exists shared_tda jsonb;

