-- Чим закрилась угода: тейк, стоп, руками чи стоп-аут.
--
-- MT5 знає це точно — у кожної угоди закриття є `reason`, — але досі
-- ця інформація до журналу не доїжджала, і відрізнити «взяв тейк» від
-- «закрив руками в тому ж місці» було неможливо. А різниця саме та,
-- заради якої журнал і ведуть: дві однакові за грошима угоди можуть
-- бути протилежними за дисципліною.
--
-- Значення: tp | sl | manual | expert | stopout | other.
-- Текстом, а не enum: словник ще буде рости (часткові закриття,
-- трейлінг), і кожне розширення enum — це блокування таблиці.

alter table public.trades
  add column if not exists exit_reason text;

comment on column public.trades.exit_reason is
  'Як закрилась позиція за даними термінала: tp | sl | manual | expert | stopout | other';
