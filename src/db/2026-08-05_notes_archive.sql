-- EDGE JOURNAL — архів нотаток
-- Виконати у Supabase → SQL Editor. Ідемпотентний.
--
-- З фідбеку: «зручно не просто видаляти, а ще архівувати нотатки —
-- як типу виконані або взяті до відома, але зберегти».
--
-- Раніше в нотатки була одна дорога назовні — видалення. Через це
-- відпрацьовані записи або висіли перед очима, або зникали назавжди
-- разом із контекстом, до якого колись хочеться повернутись.
--
-- Прапорець, а не окрема таблиця: нотатка не змінює своєї природи
-- від того, що її прибрали з очей. Теги, картинки, пошук — усе має
-- працювати по ній так само, просто вона не потрапляє в основну
-- стрічку. Окрема таблиця означала б дублювання всіх запитів.
-- ==================================================================

alter table public.notes
  add column if not exists archived boolean not null default false;

-- Основна стрічка тепер завжди читає з умовою archived = false, і
-- індекс має це враховувати, інакше на великому записнику фільтр
-- дожовував би весь набір рядків.
create index if not exists notes_user_active_idx
  on public.notes (user_id, note_date desc, created_at desc)
  where archived = false;
