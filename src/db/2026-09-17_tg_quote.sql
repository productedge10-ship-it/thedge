-- Ранкова фраза в Telegram.
--
-- Окремий прапорець, а не частина `tg_plan_on`: нагадування про план —
-- це робота, фраза — настрій. Людина цілком може хотіти одне без
-- іншого, і сховати їх за одним вимикачем означає змусити вибирати
-- там, де вибору бути не мало.
--
-- Типово увімкнено: це один рядок на добу, який нічого не вимагає у
-- відповідь. Вимкнути його — один дотик на екрані «Нагадування».

alter table public.user_settings
  add column if not exists tg_quote_on boolean not null default true;
