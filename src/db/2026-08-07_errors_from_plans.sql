--
-- Помилка з угоди вже їде в журнал (2026-08-05_errors_from_trades),
-- а помилка з пост-сесійної діагностики — ні. Вона лишалась усередині
-- `plan_data` того дня і не існувала більше ніде: ні в стрічці
-- журналу, ні в статистиці, ні в тижневому розборі.
--
-- Це гірше, ніж просто пропущений зв'язок. Діагностика питає «була
-- помилка в читанні структури?» одразу після сесії — тобто в момент,
-- коли людина ще пам'ятає, що саме сталось. Найчесніші відповіді
-- писались туди, звідки їх ніхто потім не читав.
-- ==================================================================

alter table public.trade_errors
  -- on delete cascade: план видалили — вигаданого дня більше немає,
  -- і помилка, прив'язана до нього, теж ні до чого не належить.
  add column if not exists plan_id uuid references public.trading_plans(id) on delete cascade;

-- Один запис на план, як і один на угоду. Діагностика заповнюється
-- раз на день і переписується, а не додається — тому при кожному
-- збереженні плану має оновлюватись той самий рядок.
create unique index if not exists trade_errors_plan_uniq
  on public.trade_errors (plan_id)
  where plan_id is not null;

