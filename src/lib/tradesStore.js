import { supabase } from './supabase';

/* ==================================================================
   Видалення угоди.

   Одна функція на весь застосунок, бо видаляти можна з двох місць —
   кошиком у рядку таблиці й кнопкою в картці угоди. Поки логіка
   жила в обох, вони встигли розійтись: у таблиці видалення було
   обережне, з перевіркою user_id, а в картці — просто за id.
================================================================== */

/* Видалити угоду так, щоб вона не повернулась.

   Головне тут — друга дія, а не перша. Імпортовану угоду мало
   стерти: воркер щопівгодини заливає вікно історії наново і за
   двадцять хвилин вставить її назад. Ззовні це читається не як
   особливість імпорту, а як зламана кнопка — угода зникла, людина
   пішла, повернулась, і вона знову на місці.

   Тому спершу ставимо надгробок (tradesDeleted), і лише потім
   видаляємо. Порядок саме такий: якщо між двома запитами щось
   впаде, краще мати зайвий надгробок без угоди (наступний імпорт
   просто не принесе її — і це ще й правильна поведінка), ніж
   видалену угоду без надгробка, яка мовчки повернеться.

   Ручних угод це не стосується: у них немає external_id, і
   повертати їх нікому.
*/
export async function deleteTrade(trade, userId) {
  if (!trade?.id) return;

  if (trade.external_id && userId) {
    const { error } = await supabase.from('trades_deleted').upsert(
      {
        user_id: userId,
        source: trade.source || 'mt5',
        external_id: trade.external_id,
      },
      { onConflict: 'user_id,source,external_id' },
    );
    /* Не кидаємо: надгробок — це про «щоб не повернулась», а не про
       «щоб видалилась». Якщо він не ліг, угоду все одно треба
       прибрати з очей — людина попросила саме це. */
    if (error) console.error('trades_deleted', error);
  }

  /* user_id у самому видаленні — не зайва обережність: адмінська
     політика дає право читати чужі рядки, і один невдалий id міг би
     стерти чужу угоду. */
  let q = supabase.from('trades').delete().eq('id', trade.id);
  if (userId) q = q.eq('user_id', userId);

  const { error } = await q;
  if (error) throw error;
}

/* Передумали.

   Прибираємо надгробок — і найближча синхронізація принесе угоду
   назад із термінала. Самі нічого не відновлюємо: у нас немає її
   даних, вони лишились у брокера, і вигадувати рядок «як було»
   означало б показати людині щось схоже на її угоду замість неї. */
export async function undeleteTrade({ source, external_id: externalId }, userId) {
  if (!externalId || !userId) return;
  await supabase.from('trades_deleted').delete()
    .eq('user_id', userId)
    .eq('source', source || 'mt5')
    .eq('external_id', externalId);
}
