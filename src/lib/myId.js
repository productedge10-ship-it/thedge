import { supabase } from './supabase';

/* ==================================================================
   Id поточного користувача для явного фільтра «лише мої».

   RLS — підлога, а не фільтр застосунку: у базі бувають політики,
   які законно віддають більше (адміну — все, будь-кому — поширене).
   Тому кожен список у застосунку просить свої рядки явно.

   getSession читає сесію локально, без мережі, тож це дешево.
================================================================== */
export async function myId() {
  const { data } = await supabase.auth.getSession();
  return data?.session?.user?.id || null;
}

/* q.eq('user_id', id), або запит, що гарантовано нічого не поверне,
   якщо сесії немає: краще порожньо, ніж чуже. */
export async function onlyMine(q) {
  const id = await myId();
  return q.eq('user_id', id || '00000000-0000-0000-0000-000000000000');
}
