/* ==================================================================
   Теми.

   Темна лишається рідною: журнал відкривають перед сесією й тримають
   відкритим годинами, часто вночі. Але «завжди темно» — це рішення
   за людину, а не для неї: хтось працює біля вікна вдень, комусь від
   світлого тексту на чорному ріже очі. Тому світла тема не полегшена
   копія, а повноцінна пара.

   Що тут важливо не зіпсувати:

   • Світла тема — не інверсія темної. Якщо просто перевернути,
     акцент вигорає, а межі зникають. Тому фіолетовий у світлій
     темнішає, а лінії темнішають менше, ніж тло — інакше картки
     розпливаються по фону.
   • Семантика теж зсувається. Зелений #34d399 на білому має контраст
     нижче за норму, і «плюс» перестає читатись. У світлій темі
     кольори статусів беруться глибші.
   • RGB-трійки — окремими змінними: вони йдуть усередину rgba(),
     тому мусять лишатись трійками, а не готовим кольором.
================================================================== */

