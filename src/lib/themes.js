export const PALETTES = { dark: DARK, light: LIGHT };

/* Прочитати справжнє значення токена.

   Потрібно там, де CSS-змінних не існує: canvas не вміє var(), для
   нього треба готовий колір. Тому такі місця не беруть токен із T, а
   питають обчислене значення в браузера. */
export function readToken(name, fallback) {
  try {
    const v = getComputedStyle(document.documentElement).getPropertyValue(name).trim();
    return v || fallback;
  } catch {
    return fallback;
  }
}

/* Один спільний таймер на всі виклики: якщо людина швидко клацає
   туди-сюди, попереднє зняття класу не має обірвати новий перехід. */
let themingTimer = null;

export function applyTheme(id, { animate = false } = {}) {
  const pal = PALETTES[id] || DARK;
  const root = document.documentElement;

  /* Плавний перехід самих кольорів.

     Досі підміна змінних була миттєвою: діагональ ThemeSweep лише
     розмиває момент, але під нею весь екран стрибав з темного на
     світле одним кадром — це і читалось як «різко» й «дьоргається».

     Клас .edge-theming вмикає коротку transition на властивостях
     кольору для всього дерева. Вішаємо його тільки на час переходу
     (~360 мс) — постійна transition на `*` заважала б іншим
     станам (hover, активні вкладки). На першому завантаженні
     animate=false: анімувати нема від чого, а зайвий фейд дав би
     спалах. */
  if (animate) {
    root.classList.add('edge-theming');
    if (themingTimer) clearTimeout(themingTimer);
    themingTimer = setTimeout(() => {
      root.classList.remove('edge-theming');
      themingTimer = null;
    }, 360);
  }

  Object.entries(pal).forEach(([k, v]) => root.style.setProperty(k, v));

  /* Клас — щоб окремі місця могли доналаштуватись селектором там, де
     однією змінною не обійтись (тіні, картинки, режими накладання). */
  root.classList.toggle('edge-light', id === 'light');
  root.style.colorScheme = id === 'light' ? 'light' : 'dark';
}
