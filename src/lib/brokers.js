/* Запасний варіант для НЕВІДОМОГО id.

   Раніше тут поверталась остання фірма списку — і це було тихо
   неправильно. Рахунок, привʼязаний тоді, коли в списку був інший
   набір фірм, після скорочення списку почав би підписуватись чужою
   назвою й чужим кольором. Людина бачила б «Atlas Funded» там, де в
   неї FundingPips.

   Тепер невідомий id показує сам себе. Виглядає скромно, але не
   бреше — а рядок у базі лишається робочим: воркер шукає ключ
   MT5_PATH_<ID> і скаже своє, якщо шляху немає. */
const unknown = (id) => ({
  id: id || 'other',
  name: id
    ? id.charAt(0).toUpperCase() + id.slice(1)
    : 'Інша фірма',
  domain: null,
  tint: '#6b6b78',
  icon: null,
  plate: 'dark',
});

export const brokerById = (id) => BROKERS.find((b) => b.id === id) || unknown(id);
