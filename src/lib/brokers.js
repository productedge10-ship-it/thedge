/* ==================================================================
   Проп-фірми, до яких можна підключити термінал.

   У списку рівно ті, чия збірка MT5 справді стоїть на VPS. Це не
   обережність, а чесність: у кожної фірми власний термінал, і адреси
   її серверів зашиті саме в нього. Показати в дропдауні проп, під
   який збірки немає, означає пообіцяти те, чого не буде — людина
   введе логін, почекає хвилину й отримає «сервер не знайдено» з
   правильно введеними даними.

   Тому список тут і список `MT5_PATH_*` у `.env` на сервері мусять
   збігатися. Ставиш нову збірку — дописуєш сюди рядок. Прибираєш
   звідси — прибираєш і шлях.

   `id` іде в `mt5_accounts.broker` і перетворюється на VPS у ключ
   `MT5_PATH_<ID>`.
================================================================== */

