export const relatedPosts = (post, limit = 3) => {
  if (!post) return [];
  const rest = postsFor(post.lang).filter((p) => p.slug !== post.slug);
  const score = (p) => {
    let s = p.category === post.category ? 10 : 0;
    s += p.tags.filter((t) => post.tags.includes(t)).length * 3;
    return s;
  };
  const scored = rest
    .map((p) => ({ p, s: score(p) }))
    .filter((x) => x.s > 0)
    .sort((a, b) => b.s - a.s)
    .slice(0, limit)
    .map((x) => x.p);

  /* Стаття, яка поки сама в розділі й ні з ким не ділить теги,
     інакше лишилась би без блоку «читати далі» — а це глухий кут:
     людина дочитала й нікуди не пішла. Тому добираємо свіжими. */
  if (scored.length < limit) {
    rest
      .filter((p) => !scored.includes(p))
      .slice(0, limit - scored.length)
      .forEach((p) => scored.push(p));
  }

  return scored;
};

