/* Теги для хмари внизу списку: разом із частотою, щоб рідкісні не
   стояли поруч із наскрізними однаковим кеглем. */
export const tagCloud = (lang) => {
  const counts = new Map();
  postsFor(lang).forEach((p) => {
    p.tags.forEach((t) => counts.set(t, (counts.get(t) || 0) + 1));
  });
  return [...counts.entries()]
    .map(([tag, count]) => ({ tag, count }))
    .sort((a, b) => b.count - a.count || a.tag.localeCompare(b.tag));
};

/* Схожі статті: спершу той самий розділ, потім спільні теги. Беремо
   не випадкові, бо блок «читайте також» із випадковим набором чесно
   зізнається, що нічого про статтю не знає. */
export const relatedPosts = (post, limit = 3) => {
  if (!post) return [];
  const rest = postsFor(post.lang).filter((p) => p.slug !== post.slug);
  const score = (p) => {
    let s = p.category === post.category ? 10 : 0;
    s += p.tags.filter((t) => post.tags.includes(t)).length * 3;
    return s;
  };
  const scored = rest
    .map((p) => ({ p, s: score(p) }))
    .filter((x) => x.s > 0)
    .sort((a, b) => b.s - a.s)
    .slice(0, limit)
    .map((x) => x.p);

  /* Стаття, яка поки сама в розділі й ні з ким не ділить теги,
     інакше лишилась би без блоку «читати далі» — а це глухий кут:
     людина дочитала й нікуди не пішла. Тому добираємо свіжими. */
  if (scored.length < limit) {
    rest
      .filter((p) => !scored.includes(p))
      .slice(0, limit - scored.length)
      .forEach((p) => scored.push(p));
  }

  return scored;
};

/* Скільки статей у кожному розділі — для лівого меню. Порожні
   розділи все одно показуємо: людина має бачити, що тема існує. */
export const categoryCounts = (lang) => {
  const out = {};
  CATEGORIES.forEach((c) => { out[c.id] = 0; });
  postsFor(lang).forEach((p) => { out[p.category] = (out[p.category] || 0) + 1; });
  return out;
};

/* Мови, якими ця стаття існує: сама плюс переклади. Потрібно
   перемикачу мови на сторінці статті. */
export const langsForPost = (post) => {
  if (!post) return [];
  const out = [post.lang];
  Object.keys(post.translations || {}).forEach((l) => out.push(l));
  return out;
};
