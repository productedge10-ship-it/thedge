const norm = (s) => String(s || '').toLowerCase().replace(/[ʼ'`]/g, '').trim();

/* Пошук за збігом ключів. Довші ключі важать більше: «журнал угод»
   має перемагати «журнал», інакше питання про угоди веде в помилки. */
export function findAnswer(text) {
  const q = norm(text);
  if (q.length < 2) return null;

  let best = null;
  let bestScore = 0;

  KB.forEach((e) => {
    let score = 0;
    e.keys.forEach((k) => {
      if (q.includes(norm(k))) score += k.length;
    });
    if (score > bestScore) { bestScore = score; best = e; }
  });

  /* Поріг, щоб випадковий збіг у два символи не тягнув відповідь */
  return bestScore >= 4 ? best : null;
}

