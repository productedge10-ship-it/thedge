/* Змінні ставимо на :root, а не на контейнер сторінки, і це важливо:
   модалки живуть у порталах на body, тобто поза розміткою сторінки.
   Зі змінними на корені вони фарбуються самі, без жодної правки в
   кожному вікні окремо. */
export default function useTerminalSkin() {
  const { theme } = useSettings();

  useEffect(() => {
    if (theme !== 'light') return undefined;

    const root = document.documentElement;
    Object.entries(TERMINAL).forEach(([k, v]) => root.style.setProperty(k, v));
    root.classList.add('edge-tw');

    /* На виході повертаємо загальну тему — інакше палітра потягнулась
       би за людиною в решту застосунку. */
    return () => {
      root.classList.remove('edge-tw');
      applyTheme(theme);
    };
  }, [theme]);
}
